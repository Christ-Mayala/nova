/**
 * Traduit une clé dans la langue voulue.
 * Les jetons `{nom}` sont remplacés par les valeurs fournies.
 */
export function traduire(
  langue: Langue,
  cle: string,
  valeurs?: Record<string, string | number>
): string {
  const dictionnaire = DICTIONNAIRES[langue] ?? DICTIONNAIRES[LANGUE_DEFAUT];
  const gabarit = dictionnaire[cle] ?? DICTIONNAIRES[LANGUE_DEFAUT][cle] ?? cle;
  if (!valeurs) return gabarit;
  return gabarit.replace(/\{(\w+)\}/g, (correspondance, nom: string) =>
    valeurs[nom] !== undefined ? String(valeurs[nom]) : correspondance
  );
}
